"""
Calculator Funtions
"""


def add(x, y):
    """ This functions adds 'x' and 'y' then returns the result. """
    return x + y


def subtract(x, y):
    """ This functions substracts 'y' from 'x' and then returns the result. """
    return x - y


def sub(a, b):
    """This functions substracts 'b' from 'a' \
        utilizing the `substract` function"""
    return subtract(a, b)
